package com.luxera.companion.human;

import com.luxera.companion.human.mind.MindSnapshot;

/**
 * V2.2 §3.1.4 —— <b>跨模块只读面</b>: 控制台、运维面、{@code AgentProfileProjector} 看她的方式。
 *
 * <h2>为什么给快照, 不给对象</h2>
 *
 * 它返回的是 {@link BodySnapshot} / {@link LifeSnapshot} / {@link MindSnapshot} 三个
 * <b>不可变快照</b>, 不是 {@code Body} / {@code Life} / {@code Mind} 本身。两个理由,
 * 一个比一个硬（§3.1.4 原文, 抄在这里是因为它是本接口存在的全部理由）:
 *
 * <ol>
 *   <li><b>并发。</b>{@code HumanActor} 是单线程的, 而读的人（HTTP 请求线程）不是。
 *       把可变的 {@code Body} 交出去, 等于让 HTTP 线程与 actor 线程同时读写同一片状态 ——
 *       而 {@code Body.advance()} 里是多步写入, 读到半个状态的概率并不小。
 *       具体到可以写出来: 她正从"刚睡醒"推进到"清醒", {@code state} 与
 *       {@code lastDelta} 是先后写的, 而控制台在中间那一刻读到的是
 *       "状态是新的、增量还是旧的" —— 一张不可能存在的图;</li>
 *   <li><b>方向。</b>快照是<b>只读的</b>, 所以"外部模块改了她的状态"这件事在类型上不可能。
 *       若给的是活对象, 某一天就会有人为了"让控制台能修一下她的保暖值"而加上一个
 *       setter —— 而那条写入<b>绕过了账本</b>, 于是"她为什么冷"再也答不出来。
 *       注意这条理由比第一条更不容易被绕过: 并发问题可以用一把锁兜住,
 *       而"绕过账本的写入口"一旦在类型上存在, 就迟早会被用。</li>
 * </ol>
 *
 * <h2>代价: 每次读现场构造, 不缓存</h2>
 *
 * §3.1.4 明确写了这个代价是明知的、可接受的: 控制台读的是<b>一个人的当前状态</b>,
 * 不是一万行报表。缓存反而会引入一类新问题 —— 缓存的是哪一刻?
 * 谁负责失效? 而"这一页显示的是三十秒前的她"在控制台上是一件必须能分辨的事
 * （所以三个快照都带 {@code at}）。
 *
 * <h2>它刻意不含时刻参数之外的东西</h2>
 *
 * 本接口没有 {@code now()}。快照从哪里拿时刻, 由<b>构造它的那个人</b>决定
 * （{@code Human.contextAt(Instant)} 要一个参数, 而 {@code Human.context()} 用
 * 她最后一次处理事件时的时刻）—— 接口这一层不再发明第二个时刻来源。
 * 一个能在接口上读到"现在"的快照面, 就是 §3.4.2 那类错误的入口。
 */
public interface HumanContext {

    /** 这是谁的。—— 注意它<b>不是</b> {@code String}: 见 {@link HumanId} 的说明。 */
    HumanId humanId();

    /**
     * 她身体怎么样 —— "她冷不冷、饿不饿、刚才那一下是什么在动"。
     *
     * <p>这是控制台第一页要的东西, 也是最常被读的一个。快照里带的都是
     * <b>可以画出来</b>的量（状态、增量、账本结算、通道水位、阈值报警),
     * 而不是她的内部对象。
     */
    BodySnapshot body();

    /** 她这一天在过什么日子 —— 计划表、手头那件事、最近做过的事。 */
    LifeSnapshot life();

    /**
     * 她心里在想什么 —— 注意这一份<b>不带正文</b>。
     *
     * <p>{@code MindSnapshot} 已经存在, 这里直接用它, 不重写也不"顺手加两个字段":
     * 它不进来是有意为之（"摘要一旦带上正文, 它就会开始被当成她的记忆的第二份拷贝",
     * 见其类注释）—— 快照面要加东西之前, 先读那段理由。
     */
    MindSnapshot mind();
}
