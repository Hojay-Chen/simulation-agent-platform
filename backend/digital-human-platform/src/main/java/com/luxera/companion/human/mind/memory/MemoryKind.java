package com.luxera.companion.human.mind.memory;

/**
 * V2.2 §3.4.1 —— <b>记忆的五种</b>。
 *
 * <h2>为什么这个是 enum (而事件类型不是)</h2>
 * 还是那条判据(§1.3 P4): 取值集合是由<b>本设计的内部逻辑</b>决定的, 还是由
 * <b>外部世界的多样性</b>决定的?
 *
 * <p>答案是前者, 而且理由与 {@code Modality} 不同 —— 这一点值得说清楚,
 * 否则"记忆种类可以是 enum"会被当成一个可以类推到别处的结论:
 * <ul>
 *   <li>{@code Modality} 封闭是因为<b>生理事实</b>: 人只有五种感官;</li>
 *   <li>{@code MemoryKind} 封闭是因为<b>检索结构</b>: 这五个值对应的不是"世界上有几种记忆",
 *       而是"她<b>按什么维度</b>去回忆"。这个维度由本设计决定 ——
 *       换成"按情绪检索"就是另一个设计, 而不是"世界上多了一种记忆"。</li>
 * </ul>
 * 世界上当然会不断出现新的<b>记忆</b>(今天记得实验数据, 明天记得一次争吵),
 * 但它们都落在五种检索维度之内。这与 {@code CoreEventCatalog.Category}
 * ("世界上只会不断出现新的<b>事件</b>, 不会出现第四种<b>存储结构</b>")
 * 是同一个形状的论证。
 *
 * <h2>五种各自的检索入口是什么</h2>
 * 这个名字不是分类标签, 它决定了 {@link MemoryStore} 上有哪几个方法 ——
 * 也就是说, <b>它是一份接口清单的索引</b>。这一条很重要: 如果某一"种"记忆在
 * {@code MemoryStore} 上没有对应的入口, 那它就不是一种记忆, 而只是一个字段。
 */
public enum MemoryKind {

    /**
     * 情景记忆 —— "那天发生了什么"。
     *
     * <p>检索入口按<b>时间</b>: 她不记得"12:03 那条消息的正文", 她记得
     * "今天下午她写作业写到一半, 手机响了两下, 她没看"。
     */
    EPISODIC("情景记忆", "按时间检索: 那段时间里发生了什么"),

    /**
     * 语义记忆 —— "我知道的那些事实"。
     *
     * <p>检索入口按<b>线索</b>: "图书馆九点关门"。
     * 它与情景记忆的差别不是"抽象与具体", 而是<b>它有没有发生的时刻</b> ——
     * 她知道自己住在哪儿, 但想不起是哪一天知道的。
     */
    SEMANTIC("语义记忆", "按线索检索: 我知道的事实"),

    /**
     * 共享记忆 —— "我们之间有过什么"。
     *
     * <p>检索入口按<b>人</b>。它是唯一一种<b>两个人共有的</b>记忆,
     * 而正因为它共有, 它必须单独放: 把它塞进情景记忆会让"她记得的那次晚餐"
     * 与"她也记得的那次晚餐"变成两条互不相干的记录,
     * 而"我们之间的往事"这个界面需要的是把它们合起来看。
     */
    SHARED("共享记忆", "按人检索: 我和她/他一起经历过的"),

    /**
     * 关系记忆 —— "她对我来说是什么人"。
     *
     * <p>检索入口按<b>人</b>, 但与共享记忆的区别是: 这一种记的是<b>状态</b>
     * (亲密度、信任、印象)而不是<b>事件</b>。它是 {@code Relationship} 的历史,
     * 而 {@code RelationshipGraph} 是它的当前值。
     */
    RELATIONSHIP("关系记忆", "按人检索: 我对她的看法与关系的变迁"),

    /**
     * 自我记忆 —— "我是谁、我做过什么决定"。
     *
     * <p>检索入口按<b>主题</b>。它让她能说出"我一向不太主动找人说话"这种句子 ——
     * 而那正是 persona 在长时间运行后应当<b>自己长出来</b>、而不是一直从配置里读的东西。
     */
    SELF("自我记忆", "按主题检索: 关于我自己的事实与一贯做法");

    private final String label;
    private final String retrieval;

    MemoryKind(String label, String retrieval) {
        this.label = label;
        this.retrieval = retrieval;
    }

    public String label() {
        return label;
    }

    /** 这一种记忆的检索入口 —— 见类注释"它是一份接口清单的索引"。 */
    public String retrieval() {
        return retrieval;
    }

    @Override
    public String toString() {
        return label;
    }
}
